// Renders packages/email/src/templates/messages.generated.ts from the
// `emails` namespace of every i18n/<locale>.json, plus the web app's
// notification strings listed in notificationTextPaths. The email package
// compiles with tsc and ships without i18n/, so it can't import the JSON at
// runtime.
import fs from "node:fs/promises";
import path from "node:path";
import { defaultLocale, repoRoot } from "./shared.mjs";

export const emailMessagesPath = path.join(
  repoRoot,
  "packages",
  "email",
  "src",
  "templates",
  "messages.generated.ts",
);

// Notification emails say what the inbox says: the API renders each line
// from `type` + `eventData` with the web app's own strings (as
// apps/web/src/lib/notification-text.ts does), so these subtrees are copied
// rather than translated twice.
const notificationTextPaths = [
  "notifications.events",
  "notifications.reminderLeadTime",
  "tasks.status",
  "tasks.priority",
  "ai.budget.notice.title",
  "ai.budget.notice.content",
  "ai.agents.inbox.title",
  "ai.agents.reply.title",
  "ai.agents.needsInput.notificationTitle",
];

/** A copy of `data` holding only the given dot paths. */
function pickPaths(data, paths) {
  const result = {};
  for (const dotted of paths) {
    const parts = dotted.split(".");
    const value = parts.reduce((node, part) => node?.[part], data);
    if (value === undefined) continue;
    let target = result;
    for (const part of parts.slice(0, -1)) {
      target[part] ??= {};
      target = target[part];
    }
    target[parts.at(-1)] = value;
  }
  return result;
}

const header = [
  '// Generated by scripts/i18n/emails.mjs from the "emails" namespace of',
  "// i18n/*.json and the notification strings the web app shows. Do not edit:",
  "// change the JSON, then run `pnpm i18n:emails`.",
  'import type { EmailLocale } from "./resolve-locale";',
  "",
  "const messages = {",
];

const middle = [
  "} satisfies Record<EmailLocale, object>;",
  "",
  "/** The web app's notification strings: events, status and priority names. */",
  "const notificationTexts = {",
];

const footer = [
  "} satisfies Record<EmailLocale, object>;",
  "",
  'export type EmailMessages = (typeof messages)["en"];',
  "",
  'export type NotificationTexts = (typeof notificationTexts)["en"];',
  "",
  "/** Locales may carry extra plural forms (_few, _many) that English lacks. */",
  "export function emailMessagesFor(locale: EmailLocale): EmailMessages {",
  "\treturn messages[locale] as EmailMessages;",
  "}",
  "",
  "export function notificationTextsFor(locale: EmailLocale): NotificationTexts {",
  "\treturn notificationTexts[locale] as NotificationTexts;",
  "}",
  "",
];

/** `{ source }`, or `{ missing }` listing locales without an emails namespace. */
export function renderEmailMessages(locales) {
  const missing = locales
    .filter(({ data }) => !data.emails)
    .map(({ locale }) => locale);
  if (missing.length > 0) {
    return { missing };
  }

  // Email locales are language codes; each app locale is the only one for
  // its language (see packages/email/src/templates/resolve-locale.ts).
  const byLanguage = new Map(
    locales.map(({ locale, data }) => [locale.split("-")[0], data]),
  );
  const english = defaultLocale.split("-")[0];
  const languages = [...byLanguage.keys()].sort((a, b) =>
    a === english ? -1 : b === english ? 1 : a.localeCompare(b),
  );

  const entries = (select) =>
    languages.map((language) => {
      const json = JSON.stringify(select(byLanguage.get(language)), null, "\t");
      return `\t${language}: ${json.replace(/\n/gu, "\n\t")},`;
    });

  return {
    source: [
      ...header,
      ...entries((data) => data.emails),
      ...middle,
      ...entries((data) => pickPaths(data, notificationTextPaths)),
      ...footer,
    ].join("\n"),
  };
}

export async function readEmailMessages() {
  return fs.readFile(emailMessagesPath, "utf8").catch(() => null);
}
