// Regenerates the two explicit registries of built-in project templates from
// the files on disk, so adding a template never needs a hand edit:
//
//   src/project-template/definitions/index.ts  (every definitions/<id>.ts)
//   src/project-template/locales/index.ts      (every locales/<name>.json)
//
// Usage (from the repo root):
//   pnpm --filter @margaya/api exec tsx scripts/generate-template-index.ts
//
// The output is a pure function of the directory listing, sorted by name, so
// running it again (or from several places at once) converges.

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(
  dirname(fileURLToPath(import.meta.url)),
  "../src/project-template",
);

function identifier(name: string, prefix: string): string {
  const camel = name
    .replace(/^_+/, "")
    .replace(/[^a-zA-Z0-9]+(.)?/g, (_, next: string | undefined) =>
      next ? next.toUpperCase() : "",
    );
  return `${prefix}${camel.charAt(0).toUpperCase()}${camel.slice(1)}`;
}

function writeIfChanged(path: string, content: string) {
  let current = "";
  try {
    current = readFileSync(path, "utf8");
  } catch {
    // A missing index is written below.
  }
  if (current !== content) writeFileSync(path, content);
}

const HEADER =
  "// Generated by apps/api/scripts/generate-template-index.ts from the files in\n// this folder. Do not edit by hand: run the script after adding a file.\n";

const definitionIds = readdirSync(join(root, "definitions"))
  .filter((file) => file.endsWith(".ts") && file !== "index.ts")
  .filter((file) => !file.endsWith(".test.ts"))
  .map((file) => file.slice(0, -3))
  .sort();

writeIfChanged(
  join(root, "definitions/index.ts"),
  `${HEADER}\nimport type { ProjectTemplate } from "../types";\n${definitionIds
    .map((id) => `import ${identifier(id, "template")} from "./${id}";`)
    .join(
      "\n",
    )}\n\nexport const TEMPLATE_DEFINITIONS: readonly ProjectTemplate[] = [\n${definitionIds
    .map((id) => `  ${identifier(id, "template")},`)
    .join("\n")}\n];\n`,
);

const fragmentNames = readdirSync(join(root, "locales"))
  .filter((file) => file.endsWith(".json"))
  .map((file) => file.slice(0, -5))
  .sort();

// Fragments are temporary (their text is merged into i18n/*.json), so the
// list is usually empty; write it in the formatter's shape either way.
writeIfChanged(
  join(root, "locales/index.ts"),
  fragmentNames.length === 0
    ? `${HEADER}\nimport type { LocaleFragment } from "../text";\n\nexport const LOCALE_FRAGMENTS: readonly LocaleFragment[] = [];\n`
    : `${HEADER}\nimport type { LocaleFragment } from "../text";\n${fragmentNames
        .map(
          (name) =>
            `import ${identifier(name, "fragment")} from "./${name}.json";`,
        )
        .join(
          "\n",
        )}\n\nexport const LOCALE_FRAGMENTS: readonly LocaleFragment[] = [\n${fragmentNames
        .map((name) => `  ${identifier(name, "fragment")} as LocaleFragment,`)
        .join("\n")}\n];\n`,
);

console.log(
  `Registered ${definitionIds.length} definitions and ${fragmentNames.length} locale fragments.`,
);
